/// `fpr`'s public key in a file of `dir`, for `--recipient-file`: found
/// among the user's own keys first, else in the plugin keyring, as
/// `encrypt` finds recipients. Unusable keys are refused.
fn recipient_file(engine: &Engine, own: &[KeyInfo], f: &Fpr, dir: &Path) -> Result<PathBuf> {
    let (home, key) = match own.iter().find(|k| k.fpr == f.as_str()) {
        Some(k) => (None, Some(k.clone())),
        None => {
            let home = Some(engine.recipients_home.as_path());
            let key = if engine.recipients_home.is_dir() {
                engine.public_key(home, f)?
            } else {
                None
            };
            (home, key)
        }
    };
    let key = key.ok_or_else(|| {
        Error::new(
            "unknownRecipient",
            format!("{f} hasn't been imported (importPublic) and isn't one of your keys"),
        )
    })?;
    if let Some(why) = key.unusable_for_encryption() {
        return Err(Error::new("recipientUnusable", format!("{f} {why}")));
    }
    let exported = engine.export(home, f)?;
    if exported.is_empty() {
        return Err(Error::new(
            "unknownRecipient",
            format!("couldn't export {f}"),
        ));
    }
    let path = dir.join(format!("{}.gpg", f.as_str()));
    std::fs::write(&path, exported).map_err(|e| io_err(path.display(), e))?;
    Ok(path)
}

/// `data` encrypted to the one key in `recipient`: binary OpenPGP, no
/// signature, as `gpg --batch -o FILE -r 0x<FPR> -e` writes it for
/// git-crypt. `--no-encrypt-to` keeps a default recipient from the user's
/// gpg.conf out of a file named for someone else.
fn encrypt_to(engine: &Engine, recipient: &Path, data: &[u8]) -> Result<Vec<u8>> {
    let args: Vec<OsString> = vec![
        "--no-encrypt-to".into(),
        "--recipient-file".into(),
        recipient.into(),
        "--encrypt".into(),
        "--output".into(),
        "-".into(),
    ];
    let out = engine.gpg.run(
        None,
        &args,
        data,
        Limits {
            timeout: QUICK,
            max_stdout: MAX_MEMBER_FILE as usize,
        },
    )?;
    let st = status::parse(&out.status);
    let has = |k: &str| st.iter().any(|s| s.keyword == k);
    if has("INV_RECP") || has("NO_RECP") {
        return Err(Error::new(
            "recipientUnusable",
            format!("gpg refused the recipient ({})", out.last_log_line()),
        ));
    }
    if !out.success || !has("END_ENCRYPTION") || out.stdout.is_empty() {
        return Err(Error::new(
            "gpgFailed",
            format!(
                "gpg couldn't encrypt the vault key ({})",
                out.last_log_line()
            ),
        ));
    }
    Ok(out.stdout)
}

fn temp_dir() -> Result<tempfile::TempDir> {
    tempfile::Builder::new()
        .prefix("mahfouz-gc-")
        .tempdir()
        .map_err(|e| Error::new("io", format!("temporary directory: {e}")))
}

/// `initVault`: a new key for the vault, encrypted to each member. Writes
/// the key file, the member files and `.git-crypt/.gitattributes`, and
/// configures the filters; the app writes the root `.gitattributes` block,
/// renormalizes and commits. Every gpg step runs before anything is
/// written, and a failure while writing removes what was written.
///
/// At least one member must be one of the user's own secret keys, so the
/// vault can be unlocked again from a fresh clone.
pub fn init(engine: &Engine, v: &Vault, members: &[String], exe: &Path) -> Result<Initialised> {
    let _g = LOCK.lock().unwrap_or_else(|p| p.into_inner());
    if v.key_path().exists() {
        return Err(Error::new(
            "alreadyInitialised",
            "this clone already has a git-crypt key",
        ));
    }
    if v.keys_dir().exists() {
        return Err(Error::new(
            "alreadyInitialised",
            "this vault already has git-crypt keys (.git-crypt/keys): unlock it instead",
        ));
    }
    let members = Fpr::parse_list(members, "members", MAX_MEMBERS)?;
    let own = engine.secret_keys()?;
    if !members
        .iter()
        .any(|m| own.iter().any(|k| k.fpr == m.as_str()))
    {
        return Err(Error::invalid(
            "at least one member must be one of your own secret keys, or no clone could be unlocked by you",
        ));
    }
    let tmp = temp_dir()?;
    let key = KeyFile::generate(None).map_err(|e| Error::new("io", format!("random key: {e}")))?;
    let data = key
        .single_version(MEMBER_VERSION)
        .expect("a generated key has version 0")
        .store();
    let mut files: Vec<(String, Vec<u8>)> = vec![];
    for f in &members {
        let r = recipient_file(engine, &own, f, tmp.path())?;
        files.push((
            Vault::member_rel(MEMBER_VERSION, f),
            encrypt_to(engine, &r, &data)?,
        ));
    }

    let state_created = !v.root.join(STATE_DIR).exists();
    let attrs_rel = format!("{STATE_DIR}/.gitattributes");
    let write = || -> Result<Vec<String>> {
        v.write_key(&key)?;
        let mut paths = vec![];
        if !v.root.join(&attrs_rel).exists() {
            v.create_file(&attrs_rel, STATE_GITATTRIBUTES.as_bytes())?;
            paths.push(attrs_rel.clone());
        }
        for (rel, bytes) in &files {
            v.create_file(rel, bytes)?;
            paths.push(rel.clone());
        }
        v.configure_filters(exe)?;
        Ok(paths)
    };
    match write() {
        Ok(paths) => Ok(Initialised {
            paths,
            gitattributes: ROOT_GITATTRIBUTES.to_string(),
        }),
        Err(e) => {
            let _ = std::fs::remove_file(v.key_path());
            let _ = v.deconfigure_filters();
            let _ = std::fs::remove_dir_all(v.keys_dir());
            if state_created {
                let _ = std::fs::remove_dir_all(v.root.join(STATE_DIR));
            }
            Err(e)
        }
    }
}

/// `addVaultMember`: the unlocked key's newest version, encrypted to
/// `fpr`, like `git-crypt add-gpg-user`. A member who already has a file is
/// left as they are (no paths).
pub fn add_member(engine: &Engine, v: &Vault, fpr: &str) -> Result<Changed> {
    let _g = LOCK.lock().unwrap_or_else(|p| p.into_inner());
    let f = Fpr::parse(fpr)?;
    let key = match v.load_key() {
        None => {
            return Err(Error::new(
                "locked",
                "unlock the vault before adding a member",
            ))
        }
        Some(r) => r.map_err(key_error)?,
    };
    if key.key_name.is_some() {
        return Err(Error::new(
            "malformedKey",
            "the key file is for a named key, not the default one",
        ));
    }
    let entry = key
        .latest()
        .ok_or_else(|| Error::new("malformedKey", "the key file is empty"))?;
    let rel = Vault::member_rel(entry.version, &f);
    let mut paths = vec![];
    if !v.root.join(&rel).exists() {
        let own = engine.secret_keys()?;
        let tmp = temp_dir()?;
        let r = recipient_file(engine, &own, &f, tmp.path())?;
        let data = key
            .single_version(entry.version)
            .expect("latest exists")
            .store();
        let bytes = encrypt_to(engine, &r, &data)?;
        v.create_file(&rel, &bytes)?;
        paths.push(rel);
    }
    let attrs_rel = format!("{STATE_DIR}/.gitattributes");
    if !paths.is_empty() && !v.root.join(&attrs_rel).exists() {
        v.create_file(&attrs_rel, STATE_GITATTRIBUTES.as_bytes())?;
        paths.push(attrs_rel);
    }
    Ok(Changed { paths })
}

/// `removeVaultMember`: deletes `fpr`'s member file. The key isn't
/// rotated: whoever had it, or a clone with an old member file, can still
/// decrypt everything committed until the key changes. The last member
/// can't be removed.
pub fn remove_member(v: &Vault, fpr: &str) -> Result<Changed> {
    let _g = LOCK.lock().unwrap_or_else(|p| p.into_inner());
    let f = Fpr::parse(fpr)?;
    let members = v.members()?;
    if !members.contains(&f) {
        return Err(Error::new(
            "notAMember",
            format!("{f} isn't a member of this vault"),
        ));
    }
    if members.len() == 1 {
        return Err(Error::new(
            "lastMember",
            "the last member can't be removed: no one could unlock the vault",
        ));
    }
    let rel = Vault::member_rel(MEMBER_VERSION, &f);
    let path = v.root.join(&rel);
    std::fs::remove_file(&path).map_err(|e| io_err(path.display(), e))?;
    Ok(Changed { paths: vec![rel] })
}

