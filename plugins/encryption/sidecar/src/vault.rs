//! Whole-vault encryption: the vault's git repository encrypted with
//! git-crypt's scheme, in git-crypt's own layout, so the real `git-crypt`
//! reads it and this sidecar reads repositories `git-crypt` made.
//!
//! The layout (git-crypt 0.8.0, `commands.cpp`):
//!
//! - `.git/git-crypt/keys/default`: the unlocked symmetric key file
//!   (`get_internal_key_path`, lines 240-278), local to the clone, 0600.
//! - `.git-crypt/keys/default/0/<FPR>.gpg`: the key file holding only
//!   version 0, encrypted (binary OpenPGP, not armored) to one member's GPG
//!   key, named by its primary key's fingerprint as gpg prints it
//!   (`encrypt_repo_key`, lines 678-703; `gpg_encrypt_to_file`, `gpg.cpp`
//!   157-175). Committed: whoever holds one of those secret keys can
//!   unlock (`decrypt_repo_key`, lines 613-649).
//! - `.git-crypt/.gitattributes`: keeps that directory out of the filter
//!   (`add_gpg_user`, lines 1264-1279).
//! - git config `filter.git-crypt.smudge`/`.clean`/`.required` and
//!   `diff.git-crypt.textconv`, the binary's absolute path quoted with
//!   `escape_shell_arg` (`configure_git_filters`, lines 156-175), present
//!   only while the clone is unlocked.
//!
//! What this module doesn't do, by design: commit, check files out, or edit
//! the root `.gitattributes`. The app does those (`vault.commitFiles`,
//! `git.forceCheckout`), under its own locks, from the paths and the
//! attributes block each method returns. git-crypt's `unlock` and `lock`
//! check the encrypted files out themselves (lines 1094-1103, 1189-1198),
//! touching them first so git rewrites them; the app's forced checkout must
//! do the same.

