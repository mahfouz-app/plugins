/// One vault operation at a time: two inits racing, or an unlock and a
/// lock, would leave a key file and config that don't match.
static LOCK: Mutex<()> = Mutex::new(());

/// The repository state directory (git-crypt's default; a
/// `git-crypt.repoStateDir` setting is refused, see [`Vault::open`]).
pub const STATE_DIR: &str = ".git-crypt";

/// `.git-crypt/.gitattributes`, exactly as `git-crypt add-gpg-user` writes
/// it.
pub const STATE_GITATTRIBUTES: &str =
    "# Do not edit this file.  To specify the files to encrypt, create your own\n\
# .gitattributes file in the directory where your files are.\n\
* !filter !diff\n\
*.gpg binary\n";

/// The block the app writes into the vault's root `.gitattributes`: every
/// file through the filter except the attributes files and git-crypt's own
/// directory.
pub const ROOT_GITATTRIBUTES: &str = "* filter=git-crypt diff=git-crypt\n\
.gitattributes !filter !diff\n\
.git-crypt/** !filter !diff\n";

/// Members of one vault.
pub const MAX_MEMBERS: usize = 64;
/// A member file is a key file (about 150 bytes) under OpenPGP.
const MAX_MEMBER_FILE: u64 = 1024 * 1024;
/// The key version members are read from (git-crypt's `unlock` hard-codes
/// it too: `commands.cpp:1067-1070`).
const MEMBER_VERSION: u32 = 0;

/// Unlocking may wait on pinentry or a card touch.
const INTERACTIVE: Duration = Duration::from_secs(180);
const QUICK: Duration = Duration::from_secs(30);

fn io_err(what: impl std::fmt::Display, e: std::io::Error) -> Error {
    Error::new("io", format!("{what}: {e}"))
}

/// A vault's working tree and git directory.
#[derive(Debug, Clone)]
pub struct Vault {
    pub root: PathBuf,
    pub git_dir: PathBuf,
}

impl Vault {
    /// `vault` must be an absolute path to a directory with a `.git`. Its
    /// git directory is `git rev-parse --git-dir` there, as git-crypt finds
    /// it.
    pub fn open(vault: &str) -> Result<Self> {
        let root = PathBuf::from(vault);
        if !root.is_absolute() {
            return Err(Error::invalid("vault must be an absolute path"));
        }
        if !root.is_dir() || !root.join(".git").exists() {
            return Err(Error::new(
                "notAVault",
                format!("{vault} isn't a directory with a git repository"),
            ));
        }
        let out = git(&root, &["rev-parse", "--git-dir"])?;
        if !out.status.success() {
            return Err(git_failure("rev-parse --git-dir", &out));
        }
        let dir = String::from_utf8_lossy(&out.stdout).trim().to_string();
        if dir.is_empty() {
            return Err(Error::new(
                "gitFailed",
                "git rev-parse --git-dir printed nothing",
            ));
        }
        let dir = PathBuf::from(dir);
        let git_dir = if dir.is_absolute() {
            dir
        } else {
            root.join(dir)
        };
        let v = Vault { root, git_dir };
        // git-crypt can keep its state elsewhere; members written here
        // would then be ones `git-crypt unlock` never looks at.
        if v.config_get("git-crypt.repoStateDir")?.is_some() {
            return Err(Error::new(
                "unsupported",
                "this repository sets git-crypt.repoStateDir, which isn't supported",
            ));
        }
        Ok(v)
    }

    /// `.git/git-crypt/keys/default`.
    pub fn key_path(&self) -> PathBuf {
        crate::filter::internal_key_path(&self.git_dir, None)
    }

    fn keys_dir(&self) -> PathBuf {
        self.root.join(STATE_DIR).join("keys")
    }

    /// `.git-crypt/keys/default/<version>/<FPR>.gpg`, vault-relative.
    fn member_rel(version: u32, fpr: &Fpr) -> String {
        format!("{STATE_DIR}/keys/default/{version}/{}.gpg", fpr.as_str())
    }

    /// The members: `.git-crypt/keys/default/0/*.gpg` named by a
    /// fingerprint, upper-case and sorted.
    pub fn members(&self) -> Result<Vec<Fpr>> {
        let dir = self
            .keys_dir()
            .join("default")
            .join(MEMBER_VERSION.to_string());
        let entries = match std::fs::read_dir(&dir) {
            Ok(e) => e,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(vec![]),
            Err(e) => return Err(io_err(dir.display(), e)),
        };
        let mut out = vec![];
        for entry in entries.flatten() {
            let name = entry.file_name();
            let Some(stem) = name.to_str().and_then(|n| n.strip_suffix(".gpg")) else {
                continue;
            };
            if !entry.file_type().is_ok_and(|t| t.is_file()) {
                continue;
            }
            if let Ok(f) = Fpr::parse(stem) {
                if !out.contains(&f) {
                    out.push(f);
                }
            }
        }
        out.sort();
        Ok(out)
    }

    /// The key names with a directory under `.git-crypt/keys`.
    pub fn key_names(&self) -> Result<Vec<String>> {
        let dir = self.keys_dir();
        let entries = match std::fs::read_dir(&dir) {
            Ok(e) => e,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(vec![]),
            Err(e) => return Err(io_err(dir.display(), e)),
        };
        let mut out: Vec<String> = entries
            .flatten()
            .filter(|e| e.file_type().is_ok_and(|t| t.is_dir()))
            .filter_map(|e| e.file_name().to_str().map(str::to_string))
            .filter(|n| n == "default" || gitcrypt::valid_key_name(n))
            .collect();
        out.sort();
        Ok(out)
    }

    /// The unlocked key file, if there is one.
    fn load_key(&self) -> Option<std::result::Result<KeyFile, gitcrypt::KeyError>> {
        let data = std::fs::read(self.key_path()).ok()?;
        Some(KeyFile::load(&data))
    }

    fn config_get(&self, name: &str) -> Result<Option<String>> {
        let out = git(&self.root, &["config", "--get", name])?;
        match out.status.code() {
            Some(0) => Ok(Some(
                String::from_utf8_lossy(&out.stdout).trim_end().to_string(),
            )),
            Some(1) => Ok(None),
            _ => Err(git_failure("config --get", &out)),
        }
    }

    fn config_set(&self, name: &str, value: &str) -> Result<()> {
        let out = git(&self.root, &["config", name, value])?;
        if !out.status.success() {
            return Err(git_failure("config", &out));
        }
        Ok(())
    }

    /// Whether any key of `section` (`filter.git-crypt`) is set.
    fn has_section(&self, section: &str) -> Result<bool> {
        let pattern = format!("^{}\\.", section.replace('.', "\\."));
        let out = git(&self.root, &["config", "--get-regexp", &pattern])?;
        match out.status.code() {
            Some(0) => Ok(true),
            Some(1) => Ok(false),
            _ => Err(git_failure("config --get-regexp", &out)),
        }
    }

    /// `configure_git_filters` for the default key.
    fn configure_filters(&self, exe: &Path) -> Result<()> {
        let exe = exe.to_str().ok_or_else(|| {
            Error::new(
                "io",
                "this binary's path isn't UTF-8, so git can't be told to run it",
            )
        })?;
        let esc = escape_shell_arg(exe);
        self.config_set("filter.git-crypt.smudge", &format!("{esc} smudge"))?;
        self.config_set("filter.git-crypt.clean", &format!("{esc} clean"))?;
        self.config_set("filter.git-crypt.required", "true")?;
        self.config_set("diff.git-crypt.textconv", &format!("{esc} diff"))?;
        Ok(())
    }

    /// `deconfigure_git_filters` for the default key.
    fn deconfigure_filters(&self) -> Result<()> {
        for section in ["filter.git-crypt", "diff.git-crypt"] {
            if self.has_section(section)? {
                let out = git(&self.root, &["config", "--remove-section", section])?;
                if !out.status.success() {
                    return Err(git_failure("config --remove-section", &out));
                }
            }
        }
        Ok(())
    }

    fn filters_configured(&self) -> Result<bool> {
        Ok(self
            .config_get("filter.git-crypt.smudge")?
            .is_some_and(|v| !v.trim().is_empty())
            && self
                .config_get("filter.git-crypt.clean")?
                .is_some_and(|v| !v.trim().is_empty()))
    }

    /// Whether the root `.gitattributes` or `info/attributes` routes paths
    /// through a git-crypt filter (nested attributes files aren't read).
    fn attributes_route(&self) -> bool {
        [
            self.root.join(".gitattributes"),
            self.git_dir.join("info").join("attributes"),
        ]
        .iter()
        .filter_map(|p| std::fs::read_to_string(p).ok())
        .any(|text| {
            text.lines()
                .map(str::trim)
                .filter(|l| !l.is_empty() && !l.starts_with('#'))
                .any(|l| {
                    l.split([' ', '\t']).skip(1).any(|t| {
                        t.strip_prefix("filter=")
                            .is_some_and(|n| n == "git-crypt" || n.starts_with("git-crypt-"))
                    })
                })
        })
    }

    /// Writes the unlocked key file: 0600, in 0700 directories, replaced
    /// atomically.
    fn write_key(&self, key: &KeyFile) -> Result<()> {
        let keys = self.key_path();
        let keys_dir = keys.parent().expect("…/keys/default has a parent");
        for dir in [keys_dir.parent().expect("…/git-crypt"), keys_dir] {
            std::fs::DirBuilder::new()
                .recursive(true)
                .mode(0o700)
                .create(dir)
                .map_err(|e| io_err(dir.display(), e))?;
            std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700))
                .map_err(|e| io_err(dir.display(), e))?;
        }
        write_atomic(&keys, &key.store(), 0o600)
    }

    /// Creates `rel` (with its parent directories) holding `data`; the
    /// file must not exist yet.
    fn create_file(&self, rel: &str, data: &[u8]) -> Result<()> {
        let path = self.root.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| io_err(parent.display(), e))?;
        }
        write_atomic(&path, data, 0o644)
    }
}

/// Writes `data` to a temporary file beside `path`, then renames it over
/// `path`, so a reader never sees half a file.
fn write_atomic(path: &Path, data: &[u8], mode: u32) -> Result<()> {
    let dir = path.parent().unwrap_or(Path::new("."));
    let mut tmp = tempfile::Builder::new()
        .prefix(".mahfouz-tmp-")
        .permissions(std::fs::Permissions::from_mode(mode))
        .tempfile_in(dir)
        .map_err(|e| io_err(dir.display(), e))?;
    tmp.write_all(data)
        .and_then(|_| tmp.as_file().sync_all())
        .map_err(|e| io_err(path.display(), e))?;
    tmp.persist(path)
        .map_err(|e| io_err(path.display(), e.error))?;
    Ok(())
}

/// git in the vault, with no `GIT_DIR`/`GIT_WORK_TREE` from the
/// environment: `vault` alone says which repository.
fn git(root: &Path, args: &[&str]) -> Result<Output> {
    Command::new("git")
        .args(args)
        .current_dir(root)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .env_remove("GIT_INDEX_FILE")
        .output()
        .map_err(|e| Error::new("gitFailed", format!("couldn't run git: {e}")))
}

fn git_failure(what: &str, out: &Output) -> Error {
    let err = String::from_utf8_lossy(&out.stderr);
    let line: String = err.lines().last().unwrap_or("").chars().take(300).collect();
    Error::new("gitFailed", format!("git {what} failed: {line}"))
}

fn key_error(e: gitcrypt::KeyError) -> Error {
    Error::new("malformedKey", e.to_string())
}

#[derive(Debug, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct VaultStatus {
    /// The vault has git-crypt state (`.git-crypt/keys/*`) or its
    /// attributes route files through git-crypt.
    pub encrypted: bool,
    /// This clone has a readable key file and the filters configured.
    pub unlocked: bool,
    /// The key names under `.git-crypt/keys` (`default` for this plugin's).
    pub key_names: Vec<String>,
    /// The fingerprints that can unlock the default key.
    pub members: Vec<String>,
}

/// `vaultStatus`. Needs no gpg.
pub fn status(v: &Vault) -> Result<VaultStatus> {
    let key_names = v.key_names()?;
    let members = v.members()?.into_iter().map(|f| f.to_string()).collect();
    let key_ok = matches!(v.load_key(), Some(Ok(k)) if k.latest().is_some());
    Ok(VaultStatus {
        encrypted: !key_names.is_empty() || v.attributes_route(),
        unlocked: key_ok && v.filters_configured()?,
        key_names,
        members,
    })
}

#[derive(Debug, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct Unlocked {
    /// The member file that was decrypted (`None` when the clone already
    /// had its key).
    pub member: Option<String>,
    pub already_unlocked: bool,
}

/// `unlockVault`: decrypts the member file of one of the user's secret
/// keys with their gpg (pinentry may ask), installs the key file and
/// configures the filters to run `exe`. The working tree is left as it is.
pub fn unlock(engine: &Engine, v: &Vault, exe: &Path) -> Result<Unlocked> {
    let _g = LOCK.lock().unwrap_or_else(|p| p.into_inner());
    if let Some(Ok(k)) = v.load_key() {
        if k.key_name.is_none() && k.get(MEMBER_VERSION).is_some() {
            v.configure_filters(exe)?;
            return Ok(Unlocked {
                member: None,
                already_unlocked: true,
            });
        }
    }
    let members = v.members()?;
    if members.is_empty() {
        return Err(Error::new(
            "notInitialised",
            "this vault has no members (.git-crypt/keys/default/0 is empty)",
        ));
    }
    // In the order gpg lists the user's secret keys, as git-crypt tries them.
    let own = engine.secret_keys()?;
    let candidates: Vec<Fpr> = own
        .iter()
        .filter_map(|k| Fpr::parse(&k.fpr).ok())
        .filter(|f| members.contains(f))
        .collect();
    if candidates.is_empty() {
        return Err(Error::new(
            "noMemberKey",
            format!(
                "none of your secret keys is one of this vault's {} member(s)",
                members.len()
            ),
        ));
    }
    let mut last = None;
    for f in candidates {
        let path = v.root.join(Vault::member_rel(MEMBER_VERSION, &f));
        match decrypt_member(engine, &path) {
            Ok(file) => {
                // `decrypt_repo_key`'s checks (`commands.cpp:631-637`).
                let entry = file.get(MEMBER_VERSION).cloned().ok_or_else(|| {
                    Error::new(
                        "malformedKey",
                        "the member key file doesn't hold key version 0",
                    )
                })?;
                if file.key_name.is_some() {
                    return Err(Error::new(
                        "malformedKey",
                        "the member key file is for a named key, not the default one",
                    ));
                }
                let mut key = KeyFile::default();
                key.add(entry);
                v.write_key(&key)?;
                v.configure_filters(exe)?;
                return Ok(Unlocked {
                    member: Some(f.to_string()),
                    already_unlocked: false,
                });
            }
            Err(e) if e.code == "cancelled" => return Err(e),
            Err(e) => last = Some(e),
        }
    }
    Err(last.expect("at least one candidate was tried"))
}

fn decrypt_member(engine: &Engine, path: &Path) -> Result<KeyFile> {
    let meta = std::fs::metadata(path).map_err(|e| io_err(path.display(), e))?;
    if meta.len() > MAX_MEMBER_FILE {
        return Err(Error::new(
            "malformedKey",
            format!("{} is too large for a key file", path.display()),
        ));
    }
    let data = std::fs::read(path).map_err(|e| io_err(path.display(), e))?;
    let out = engine.gpg.run(
        None,
        &[OsString::from("--decrypt")],
        &data,
        Limits {
            timeout: INTERACTIVE,
            max_stdout: MAX_MEMBER_FILE as usize,
        },
    )?;
    status::judge_decrypt(&status::parse(&out.status))?;
    if !out.success {
        return Err(Error::new(
            "decryptionFailed",
            format!("gpg couldn't decrypt {}", path.display()),
        ));
    }
    KeyFile::load(&out.stdout).map_err(key_error)
}

#[derive(Debug, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct Locked {
    pub was_unlocked: bool,
}

/// `lockVault`: removes the key file and the filter config. Re-checking
/// out the files (to ciphertext) is the app's job, and it must commit
/// anything pending first: once the key is gone, nothing can be cleaned.
pub fn lock(v: &Vault) -> Result<Locked> {
    let _g = LOCK.lock().unwrap_or_else(|p| p.into_inner());
    let path = v.key_path();
    let was_unlocked = match std::fs::remove_file(&path) {
        Ok(()) => true,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => false,
        Err(e) => return Err(io_err(path.display(), e)),
    };
    v.deconfigure_filters()?;
    Ok(Locked { was_unlocked })
}

